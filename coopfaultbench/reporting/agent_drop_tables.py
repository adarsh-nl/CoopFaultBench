"""Agent drop, fixed vs. union reference: one table from
``agent_drop_fixed_vs_union.json``.

18 rows = 3 models x p_drop {0.25, 0.50, 0.75} x IoU {0.5, 0.7}. The
payload's ``none`` tier (p_drop = 0, where both references coincide) is not
a row. Every printed number is a payload field, rounded to 4 decimals:

* ``AP_union`` = ``models.<m>.tiers.<tier>.<iou>.ap_union.mean``
* ``AP_fixed`` = ``...ap_fixed.mean``
* ``dAP``      = ``...mean`` (the mean over draws of the per-draw
  difference AP_fixed - AP_union; taken from the payload, not recomputed
  from the two rounded means)
* each bracket = the matching ``ci`` pair. Despite the key name, it is the
  2.5-97.5 percentile range of the M Monte Carlo agent-drop draws: a Monte
  Carlo agent-draw range, NOT a confidence interval.

No per-stratum values are printed.
"""
from __future__ import annotations

import csv
import io

PUBLIC_PAYLOAD = 'results/payloads/agent_drop_fixed_vs_union.json'
MODELS = ('cobevt', 'v2xvit', 'where2comm')
MODEL_LABEL = {'cobevt': 'CoBEVT', 'v2xvit': 'V2X-ViT',
               'where2comm': 'Where2comm'}
TIERS = ('mild', 'moderate', 'severe')
IOUS = ('0.5', '0.7')
RANGE_LABEL = 'Monte Carlo agent-draw range (not a confidence interval)'


def fmt(x):
    return '%.4f' % x


def fmt_signed(x):
    return '%+.4f' % x


def rows(payload):
    """The 18 table rows as dicts of payload values (unrounded)."""
    out = []
    for model in MODELS:
        m = payload['models'][model]
        for tier in TIERS:
            for iou in IOUS:
                c = m['tiers'][tier][iou]
                out.append({
                    'model': model,
                    'tier': tier,
                    'p_drop': payload['tiers'][tier],
                    'iou': iou,
                    'n_draws': payload['M'],
                    'ap_union': c['ap_union']['mean'],
                    'ap_union_range': tuple(c['ap_union']['ci']),
                    'ap_fixed': c['ap_fixed']['mean'],
                    'ap_fixed_range': tuple(c['ap_fixed']['ci']),
                    'dap': c['mean'],
                    'dap_range': tuple(c['ci']),
                })
    if len(out) != 18:
        raise ValueError('expected 18 agent-drop rows, got %d' % len(out))
    return out


def _frames_phrase(payload):
    n = [payload['models'][m]['n_frames'] for m in MODELS]
    if len(set(n)) == 1:
        return '%d frames per model' % n[0]
    return 'frames per model: ' + ', '.join(
        '%s %d' % (MODEL_LABEL[m], k) for m, k in zip(MODELS, n))


def _cell(mean, rng, signed=False):
    f = fmt_signed if signed else fmt
    return '%s [%s, %s]' % (f(mean), f(rng[0]), f(rng[1]))


def build_tex(payload):
    lines = [
        r'% auto-generated by scripts/make_tables.py -- do not hand-edit',
        r'\begin{table}[t]', r'\centering', r'\small',
        r'\resizebox{\textwidth}{!}{%',
        r'\begin{tabular}{lcc|ccc}', r'\toprule',
        (r'Model & $p_{\mathrm{drop}}$ & IoU & AP$_{\mathrm{union}}$ [range] & '
         r'AP$_{\mathrm{fixed}}$ [range] & $\Delta$AP [range] \\'),
        r'\midrule',
    ]
    prev = None
    for r in rows(payload):
        if prev is not None and r['model'] != prev:
            lines.append(r'\midrule')
        prev = r['model']
        lines.append(' & '.join([
            MODEL_LABEL[r['model']], '%.2f' % r['p_drop'], r['iou'],
            _cell(r['ap_union'], r['ap_union_range']),
            _cell(r['ap_fixed'], r['ap_fixed_range']),
            _cell(r['dap'], r['dap_range'], signed=True)]) + r' \\')
    lines += [
        r'\bottomrule', r'\end{tabular}', r'}',
        (r'\caption{Agent drop scored against the fixed and the union '
         r'reference set. Each value is the mean over $M{=}%d$ Monte Carlo '
         r'agent-drop draws (seed %d; %s); $\Delta$AP $=$ '
         r'AP$_{\mathrm{fixed}} -$ AP$_{\mathrm{union}}$, computed per draw '
         r'and then averaged. Brackets: Monte Carlo agent-draw range (not a '
         r'confidence interval), i.e.\ the 2.5--97.5 percentile range of the '
         r'%d draws.}'
         % (payload['M'], payload['seed'], _frames_phrase(payload),
            payload['M'])),
        r'\label{tab:agent_drop_fixed_vs_union}', r'\end{table}',
    ]
    return '\n'.join(lines) + '\n'


def build_markdown(payload):
    out = [
        '# Agent drop: fixed vs. union reference',
        '',
        'Generated by `scripts/make_tables.py` from `%s`. '
        'Never hand-edit -- regenerate.' % PUBLIC_PAYLOAD,
        '',
        'Each value is the mean over M=%d Monte Carlo agent-drop draws '
        '(seed %d; %s). dAP = AP_fixed - AP_union, computed per draw and '
        'then averaged. Brackets: %s -- the 2.5-97.5 percentile range of '
        'the %d draws.' % (payload['M'], payload['seed'],
                           _frames_phrase(payload), RANGE_LABEL,
                           payload['M']),
        '',
        '| Model | p_drop | IoU | AP_union [range] | AP_fixed [range] '
        '| dAP [range] |',
        '|---|---|---|---|---|---|',
    ]
    for r in rows(payload):
        out.append('| ' + ' | '.join([
            MODEL_LABEL[r['model']], '%.2f' % r['p_drop'], r['iou'],
            _cell(r['ap_union'], r['ap_union_range']),
            _cell(r['ap_fixed'], r['ap_fixed_range']),
            _cell(r['dap'], r['dap_range'], signed=True)]) + ' |')
    return '\n'.join(out) + '\n'


CSV_HEADER = ['model', 'p_drop', 'iou', 'n_draws',
              'ap_union_mean', 'ap_union_mc_range_lo', 'ap_union_mc_range_hi',
              'ap_fixed_mean', 'ap_fixed_mc_range_lo', 'ap_fixed_mc_range_hi',
              'dap_mean', 'dap_mc_range_lo', 'dap_mc_range_hi']


def build_csv(payload):
    """CSV text; same values and rounding (4 decimals) as the tables. The
    ``*_mc_range_*`` columns are the Monte Carlo agent-draw range (2.5 and
    97.5 percentiles of the draws), not confidence intervals."""
    buf = io.StringIO(newline='')
    w = csv.writer(buf)
    w.writerow(CSV_HEADER)
    for r in rows(payload):
        w.writerow([r['model'], '%.2f' % r['p_drop'], r['iou'], r['n_draws'],
                    fmt(r['ap_union']), fmt(r['ap_union_range'][0]),
                    fmt(r['ap_union_range'][1]),
                    fmt(r['ap_fixed']), fmt(r['ap_fixed_range'][0]),
                    fmt(r['ap_fixed_range'][1]),
                    fmt(r['dap']), fmt(r['dap_range'][0]),
                    fmt(r['dap_range'][1])])
    return buf.getvalue()
