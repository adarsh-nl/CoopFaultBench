"""Tables built from the 109-row fault-inference grid
(``fault_inference_grid.csv``), the sanitized per-cell results
(``cells/<model>/<injector>/<tier>.json``) and the per-model fields
extracted from the grid manifest (``fault_inference_models.json``).

* model/reproduction table (``build_model_reproduction``)
* severe-tier ordering (``build_severe_tier_ordering``)
* agent drop stratified by scene agent count, union reference
  (``build_agent_drop_by_stratum``)

Rounding, applied consistently: AP 4 dp, relative drops 3 dp. Values are
formatted directly from the CSV strings / JSON numbers; nothing is pooled
except the severe-tier "Mean" column, which is the arithmetic mean of the
finite per-model entries of that row.

CoSDH has no agent-drop or missing-modality cells (those runs failed in the
released CoSDH inference path); they are reported as N/A or are absent and
are never filled.
"""
from __future__ import annotations

OPS = ['cobevt', 'v2xvit', 'where2comm', 'cosdh']
LABEL = {'cobevt': 'CoBEVT', 'v2xvit': 'V2X-ViT',
         'where2comm': 'Where2comm', 'cosdh': 'CoSDH'}
TIERS = ['mild', 'moderate', 'severe']
INJ = ['lidar_snow', 'lidar_fog', 'points_reduce', 'pose_error', 'latency',
       'missing_modality', 'agent_drop']
INJ_LABEL = {'lidar_snow': 'LiDAR snow', 'lidar_fog': 'LiDAR fog',
             'points_reduce': 'Points reduce', 'pose_error': 'Pose error',
             'latency': 'Comm. latency', 'missing_modality': 'Missing LiDAR',
             'agent_drop': 'Agent drop'}
# Cells attempted per model in the grid design (7 injectors x 3 tiers +
# clean + clean repeat + wrapped no-op + repeats), as printed in the table.
CELLS_ATTEMPTED = 26


def ap(x):
    return 'n/a' if x != x else '%.4f' % x


def rel(x):
    return 'n/a' if x != x else '%.3f' % x


def f(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return float('nan')


def esc(s):
    return (str(s).replace('_', r'\_').replace('%', r'\%')
            .replace('&', r'\&'))


def tex(label, header, rows, caption, align=None):
    """A booktabs table fragment as a string."""
    ncol = len(header)
    align = align or ('l' + 'r' * (ncol - 1))
    L = [r'% auto-generated by scripts/make_tables.py -- do not hand-edit',
         r'\begin{table}[t]', r'\centering', r'\small',
         r'\begin{tabular}{%s}' % align, r'\toprule',
         ' & '.join(esc(h) for h in header) + r' \\', r'\midrule']
    for r_ in rows:
        L.append(' & '.join(esc(c) for c in r_) + r' \\')
    L += [r'\bottomrule', r'\end{tabular}',
          r'\caption{%s}' % esc(caption),
          r'\label{tab:%s}' % label, r'\end{table}']
    return '\n'.join(L) + '\n'


def one(rows, **kw):
    hits = [r for r in rows
            if all(str(r.get(k)) == str(v) for k, v in kw.items())]
    return hits[0] if len(hits) == 1 else None


def build_model_reproduction(rows, models, cell_loader):
    """Models, shipped evaluation settings, clean AP vs. released benchmark
    values, and grid completion.

    ``rows``: grid CSV rows (strings); ``models``: the parsed
    ``fault_inference_models.json``; ``cell_loader(model, injector, tier)``
    returns a sanitized per-cell dict or None.

    Sources per column: Dataset <- ``models.<m>.dataset``; Frames, Clean AP
    <- grid row ``injector=none, severity_tier=clean``; eval loc_err / async
    / xyz-ryp std <- ``cells/<m>/none/clean.json`` ``wild_setting_shipped``
    (CoSDH records none: n/a); Pub AP <- ``models.<m>.published``; Cells <-
    number of grid rows for the model / 26 attempted; Graded <-
    ``models.<m>.graded``, with Where2comm printed as graded because it is
    graded against OpenCOOD's released V2XSet benchmark (the grid manifest's
    own flag is left as recorded).
    """
    hdr = ['Operator', 'Dataset', 'Frames', 'eval loc_err', 'eval async',
           'xyz/ryp std',
           'Clean AP@0.5', 'Clean AP@0.7', 'Pub AP@0.5', 'Pub AP@0.7',
           'Cells', 'Graded']
    body = []
    for op in OPS:
        c = one(rows, model=op, injector='none', severity_tier='clean')
        mo = models['models'][op]
        cell = cell_loader(op, 'none', 'clean')
        ws = (cell.get('wild_setting_shipped') or {}) if cell else {}
        pub = mo.get('published') or {}
        n_cells = sum(1 for r in rows if r['model'] == op)
        body.append([LABEL[op], mo['dataset'].upper(),
                     str(int(f(c['n_frames']))) if c else 'n/a',
                     str(ws.get('loc_err', 'n/a')),
                     str(ws.get('async', 'n/a')),
                     ('%s/%s' % (ws.get('xyz_std'), ws.get('ryp_std'))
                      if ws else 'n/a'),
                     ap(f(c['clean_ap50'])) if c else 'n/a',
                     ap(f(c['clean_ap70'])) if c else 'n/a',
                     ap(pub['ap50']) if pub else 'n/a',
                     ap(pub['ap70']) if pub else 'n/a',
                     '%d/%d' % (n_cells, CELLS_ATTEMPTED),
                     'yes' if (mo['graded'] or op == 'where2comm') else 'no'])
    return tex('t1_operators', hdr, body,
               'Operators, EVALUATION settings, clean accuracy against '
               'released benchmark values, and grid completion.')


def severe_value(rows, op, inj):
    """Severe-tier ``rel_drop_ap70`` for (model, injector); agent drop uses
    the scene_agent_count=2 stratum only. NaN when the cell is absent."""
    if inj == 'agent_drop':
        h = [r for r in rows if r['model'] == op
             and r['injector'] == 'agent_drop'
             and r['severity_tier'] == 'severe'
             and r['_x'].get('scene_agent_count') == '2']
        return f(h[0]['rel_drop_ap70']) if len(h) == 1 else float('nan')
    r = one(rows, model=op, injector=inj, severity_tier='severe')
    return f(r['rel_drop_ap70']) if r else float('nan')


def severe_order(rows):
    """Injectors ranked by the mean of their finite per-model values."""
    return sorted(INJ, key=lambda i: sum(
        v for v in (severe_value(rows, o, i) for o in OPS) if v == v)
        / max(1, len([v for v in (severe_value(rows, o, i) for o in OPS)
                      if v == v])))


def build_severe_tier_ordering(rows):
    """Severe-tier relative AP@0.7 drop by injector and model, ranked by
    the mean over models. Source: grid column ``rel_drop_ap70``."""
    hdr = ['Rank', 'Injector'] + [LABEL[o] for o in OPS] + ['Mean']
    body = []
    for k, inj in enumerate(severe_order(rows), 1):
        vals = [severe_value(rows, o, inj) for o in OPS]
        fin = [v for v in vals if v == v]
        mean = sum(fin) / len(fin) if fin else float('nan')
        mark = '*' if inj == 'agent_drop' else ''
        body.append([str(k), INJ_LABEL[inj] + mark]
                    + [rel(v) if v == v else 'N/A' for v in vals]
                    + [rel(mean)])
    return tex('t4_severe_ordering', hdr, body,
               'Severe-tier relative AP@0.7 drop by injector and operator, '
               'ranked by mean. Agent drop is the n=2 stratum only and its '
               'reference moves.')


def build_agent_drop_by_stratum(rows):
    """Agent drop (union reference) stratified by scene agent count, with
    the per-stratum clean reference. Sources: grid rows
    ``injector=agent_drop`` -- ``n_frames``, ``extra_metric`` n_scenes,
    ``clean_ap70`` and per-tier ``faulty_ap70``."""
    hdr = ['Operator', 'n agents', 'Frames', 'Scenarios', 'Clean AP@0.7',
           'Mild', 'Moderate', 'Severe']
    body = []
    for op in OPS:
        strata = sorted({r['_x'].get('scene_agent_count') for r in rows
                         if r['model'] == op and r['injector'] == 'agent_drop'
                         and r['_x'].get('scene_agent_count')}, key=int)
        for s in strata:
            hs = {r['severity_tier']: r for r in rows
                  if r['model'] == op and r['injector'] == 'agent_drop'
                  and r['_x'].get('scene_agent_count') == s}
            any_r = hs.get('severe') or list(hs.values())[0]
            body.append([LABEL[op], s, str(int(f(any_r['n_frames']))),
                         any_r['_x'].get('n_scenes', 'n/a'),
                         ap(f(any_r['clean_ap70']))]
                        + [ap(f(hs[t]['faulty_ap70'])) if t in hs else 'n/a'
                           for t in TIERS])
    return tex('t6_agentdrop', hdr, body,
               'Agent drop stratified by scene agent count, with per-stratum '
               'clean reference. CoSDH is absent: it has no agent-drop cells.')
