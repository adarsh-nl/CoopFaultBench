"""Per-model fault-sweep AP/Gain tables (clean + 5 fault families x 3 tiers,
AP@0.5 and AP@0.7 side by side) from ``fault_sweep_fixed_reference.json``.

Every printed number is a field of the payload:

* ``AP_indiv`` = ``models.<m>.<K>.<iou>.<cond>.ap_indiv_ci[0]``, where
  ``<K>`` is ``payloads.KEY_PER_CONDITION`` (the per-condition block)
* ``AP_CP``    = ``...ap_cp_ci[0]``
* Gain mean [lo, hi] = ``...gain_ci[0]`` [``gain_ci[1]``, ``gain_ci[2]``]

Index 0 of each ``*_ci`` triple is the MEAN over the B=1000 scenario-bootstrap
replicates (not the full-sample point estimate); indices 1 and 2 are the 2.5
and 97.5 percentiles of the same replicates.

Significance markers: * = uncorrected 95% CI excludes zero
(``uncorrected_reject``), ** = also survives Holm-Bonferroni across the
16-condition family per model and IoU (``holm_reject``).
Flags: dagger = AP_CP below Clean's own AP_CP at that IoU; double-dagger =
mean Gain < 0.
"""
from __future__ import annotations

import csv
import io

from . import payloads as pl

PUBLIC_PAYLOAD = 'results/payloads/fault_sweep_fixed_reference.json'


def esc(s):
    return str(s).replace('_', r'\_').replace('%', r'\%').replace('&', r'\&')


def fmt_ap(x):
    return '%.4f' % x


def fmt_signed(x):
    return '%+.4f' % x


def sig_marker(row):
    if row.get('holm_reject'):
        return '**'
    if row.get('uncorrected_reject'):
        return '*'
    return ''


def model_label(model):
    return {'cobevt': 'CoBEVT', 'v2xvit': 'V2X-ViT',
            'where2comm': 'Where2comm'}[model]


def build_model_table(payload, model, iou_cols=pl.IOUS):
    """Returns (latex_str, md_str) for one model's table."""
    boot_m, seed = payload['boot_M'], payload['seed']
    rows_all = pl.all_rows(payload)

    # Clean baseline AP_CP per IoU, for the dagger flag.
    clean_cp = {}
    for iou in iou_cols:
        r = rows_all[(model, 'clean', iou)]
        clean_cp[iou] = None if r['pending'] else r['ap_cp_ci'][0]

    tex_rows = []
    md_rows = []
    pending_notes = []
    for cond in pl.CONDITIONS:
        label = pl.cond_label(cond)
        tex_cells = [esc(label)]
        md_cells = [label]
        for iou in iou_cols:
            r = rows_all[(model, cond, iou)]
            if r['pending']:
                pending_notes.append('%s @%s: %s' % (label, iou, r['reason']))
                cell_tex = r'\textcolor{red!60!black}{pending}'
                tex_cells.append(r'\multicolumn{3}{c|}{%s}' % cell_tex
                                 if iou == iou_cols[0]
                                 else r'\multicolumn{3}{c}{%s}' % cell_tex)
                md_cells.append('pending (%s)' % r['reason'])
                continue
            api_m = r['ap_indiv_ci'][0]
            apc_m = r['ap_cp_ci'][0]
            g_m, g_lo, g_hi = r['gain_ci']
            sig = sig_marker(r)
            flags = ''
            if clean_cp[iou] is not None and apc_m < clean_cp[iou] \
                    and cond != 'clean':
                flags += r'\textsuperscript{\dag}'
            if g_m < 0 and cond != 'clean':
                flags += r'\textsuperscript{\ddag}'

            tex_cells += [fmt_ap(api_m), fmt_ap(apc_m),
                          r'%s%s [%s, %s]%s' % (fmt_signed(g_m), sig,
                                                fmt_signed(g_lo),
                                                fmt_signed(g_hi), flags)]
            md_cells += [fmt_ap(api_m), fmt_ap(apc_m),
                         '%s%s [%s, %s]%s' % (
                             fmt_signed(g_m), sig, fmt_signed(g_lo),
                             fmt_signed(g_hi),
                             flags.replace(r'\textsuperscript{\dag}', '†')
                             .replace(r'\textsuperscript{\ddag}', '‡'))]
        tex_rows.append(' & '.join(tex_cells) + r' \\')
        md_rows.append('| ' + ' | '.join(md_cells) + ' |')

    tex = [
        r'%% auto-generated by scripts/make_tables.py -- do not hand-edit',
        r'\begin{table}[p]', r'\centering', r'\small',
        # 7 columns overflow the text width at natural size; resizebox
        # scales the whole tabular to fit.
        r'\resizebox{\textwidth}{!}{%',
        r'\begin{tabular}{l|ccc|ccc}', r'\toprule',
        r' & \multicolumn{3}{c|}{AP@0.5} & \multicolumn{3}{c}{AP@0.7} \\',
        (r'Condition & AP$_{\mathrm{indiv}}$ & AP$_{\mathrm{CP}}$ & '
         r'$\Delta$Gain [95\% CI] & AP$_{\mathrm{indiv}}$ & AP$_{\mathrm{CP}}$ & '
         r'$\Delta$Gain [95\% CI] \\'),
        r'\midrule',
    ] + tex_rows + [
        r'\bottomrule', r'\end{tabular}', r'}',
        r'\caption{%s -- AP@0.5/@0.7 individual vs.\ CP, and $\Delta$Gain '
        r'(CP $-$ individual) with 95\%% scenario-bootstrap CI ($M{=}%d$, '
        r'seed %d), per condition. Significance: * uncorrected CI excludes '
        r'zero, ** survives Holm--Bonferroni across the 16-condition family. '
        r'\textsuperscript{\dag} AP$_{\mathrm{CP}}$ below Clean; '
        r'\textsuperscript{\ddag} mean Gain $<0$ (collaboration harm). '
        r'%s}' % (model_label(model), boot_m, seed,
                  ('Pending: %s.' % '; '.join(pending_notes)
                   if pending_notes else '')),
        r'\label{tab:fault_sweep_%s}' % model, r'\end{table}',
    ]

    md = (['# Fault sweep -- %s\n' % model_label(model),
           '| Condition | AP\\_indiv @0.5 | AP\\_CP @0.5 | Gain [CI] @0.5 | '
           'AP\\_indiv @0.7 | AP\\_CP @0.7 | Gain [CI] @0.7 |',
           '|---|---|---|---|---|---|---|'] + md_rows +
          (['', '**Pending:** ' + '; '.join(pending_notes)]
           if pending_notes else []) +
          ['', '† AP\\_CP below Clean baseline. ‡ mean Gain < 0 '
           '(collaboration harm). * uncorrected CI excludes zero, '
           '** Holm-Bonferroni-significant.'])
    return '\n'.join(tex), '\n'.join(md)


def build_markdown(payload):
    """The combined markdown document for all three models."""
    md_all = ['# Fault-crossed AP/Gain tables',
              '',
              'Generated by `scripts/make_tables.py` from `%s`. '
              'Never hand-edit -- regenerate.' % PUBLIC_PAYLOAD, '']
    for model in pl.MODELS:
        _tex, md = build_model_table(payload, model)
        md_all.append(md)
        md_all.append('')
    return '\n'.join(md_all) + '\n'


CSV_HEADER = ['condition', 'iou', 'pending', 'reason',
              'ap_individual', 'ap_cp', 'gain_mean', 'gain_ci_lo',
              'gain_ci_hi', 'uncorrected_significant', 'holm_significant']


def build_csv(payload, model):
    """Machine-readable export of one model's table: the raw payload values
    at full precision (bootstrap means and percentile bounds), as CSV text
    (``csv.writer`` defaults, CRLF line ends)."""
    rows_all = pl.all_rows(payload)
    buf = io.StringIO(newline='')
    w = csv.writer(buf)
    w.writerow(CSV_HEADER)
    for cond in pl.CONDITIONS:
        for iou in pl.IOUS:
            r = rows_all[(model, cond, iou)]
            if r['pending']:
                w.writerow([cond, iou, True, r['reason'],
                            '', '', '', '', '', '', ''])
            else:
                g = r['gain_ci']
                w.writerow([cond, iou, False, '',
                            r['ap_indiv_ci'][0], r['ap_cp_ci'][0],
                            g[0], g[1], g[2],
                            r['uncorrected_reject'], r['holm_reject']])
    return buf.getvalue()
